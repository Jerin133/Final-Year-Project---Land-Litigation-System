export const normVillage = (v) => String(v || '').toLowerCase().replace(/[^a-z]/g, '').replace(/y/g, 'i')

export const isOpen = (c) => (c.status?.english || '').toLowerCase() !== 'disposed'

export const countBy = (arr, fn) => {
  const m = new Map()
  arr.forEach((x) => {
    const k = fn(x)
    if (k != null && k !== '') m.set(k, (m.get(k) || 0) + 1)
  })
  return m
}

export function saveBlob(blob, filename) {
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = filename
  document.body.appendChild(a)
  a.click()
  a.remove()
  setTimeout(() => URL.revokeObjectURL(url), 1500)
}

export async function downloadFile(url, filename) {
  const res = await fetch(url)
  if (!res.ok) throw new Error('Download failed (' + res.status + ')')
  saveBlob(await res.blob(), filename)
}

export function downloadCsv(filename, rows) {
  const esc = (v) => `"${String(v ?? '').replace(/"/g, '""')}"`
  const csv = rows.map((r) => r.map(esc).join(',')).join('\r\n')
  saveBlob(new Blob(['\ufeff' + csv], { type: 'text/csv;charset=utf-8' }), filename)
}

export const escapeHtml = (s) =>
  String(s ?? '').replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]))

