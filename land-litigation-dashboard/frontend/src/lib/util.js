export function cleanTamilText(str) {
  if (!str || typeof str !== 'string') return str
  // 1. Remove unwanted whitespace after virama (meyyezhuthu pulli \u0BCD) before any Tamil character
  let s = str.replace(/(\u0BCD)\s+(?=[\u0B80-\u0BFF])/g, '$1')
  // 2. Remove space before dot for initials (e.g. "என் .குணசேகரன்" -> "என். குணசேகரன்")
  s = s.replace(/([\u0B80-\u0BFF])\s+\./g, '$1.')
  // 3. Normalize whitespace
  s = s.replace(/\s+/g, ' ').trim()
  return s
}

